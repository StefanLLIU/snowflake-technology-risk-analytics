-- Technology Risk: User Access Monitoring | Synthetic learning project
-- Run sections in order in a NEW SQL file. Existing source rows are preserved.
-- Sequential reruns do not insert existing IDs; existing duplicates are NOT repaired.
-- Snapshot data is current-state only: the fixed date does not reconstruct history.
-- Expected final demo: 6 grants, 5 active, 4 findings, 3 flagged grants, 60%.

-- 1. Environment
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS TECH_RISK_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;
ALTER WAREHOUSE TECH_RISK_WH SET AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
USE WAREHOUSE TECH_RISK_WH;
CREATE DATABASE IF NOT EXISTS TECH_RISK_LAB;
CREATE SCHEMA IF NOT EXISTS TECH_RISK_LAB.ACCESS_MONITORING;
USE SCHEMA TECH_RISK_LAB.ACCESS_MONITORING;

-- 2. One assessment date for the reproducible demo.
-- An expiry date is inclusive: flag it only AFTER that date.
CREATE OR REPLACE VIEW VW_ASSESSMENT_CONFIG AS
SELECT DATE '2026-09-29' AS ASSESSMENT_DATE;

-- 3. Source tables (no DROP / TRUNCATE / replacement of existing tables)

CREATE TABLE IF NOT EXISTS EMPLOYEES (
    EMPLOYEE_ID       VARCHAR(10),
    EMPLOYEE_NAME     VARCHAR(50),
    DEPARTMENT        VARCHAR(50),
    EMPLOYMENT_STATUS VARCHAR(20),
    TERMINATION_DATE  DATE
);

CREATE TABLE IF NOT EXISTS APPLICATIONS (
    APPLICATION_ID   VARCHAR(10),
    APPLICATION_NAME VARCHAR(100),
    CRITICALITY      VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS ACCESS_GRANTS (
    GRANT_ID       VARCHAR(10),
    EMPLOYEE_ID    VARCHAR(10),
    APPLICATION_ID VARCHAR(10),
    ACCESS_LEVEL   VARCHAR(20),
    IS_ACTIVE      BOOLEAN,
    ACCESS_EXPIRY_DATE DATE
);

-- Compatibility with the earlier five-column table.
ALTER TABLE ACCESS_GRANTS ADD COLUMN IF NOT EXISTS ACCESS_EXPIRY_DATE DATE;

-- 4. Seed missing IDs only. Existing edits/remediation are never reset.
-- MERGE follows Snowflake syntax: https://docs.snowflake.com/en/sql-reference/sql/merge

MERGE INTO EMPLOYEES AS t
USING (SELECT * FROM VALUES
    ('E101', 'Alex Chen', 'Finance', 'ACTIVE', NULL),
    ('E102', 'Jordan Smith', 'Technology', 'ACTIVE', NULL),
    ('E103', 'Taylor Lee', 'Finance', 'TERMINATED', '2026-09-15'),
    ('E104', 'Morgan Davis', 'Operations', 'TERMINATED', '2026-09-20'),
    ('E105', 'Casey Brown', 'Technology', 'ACTIVE', NULL)
) AS s (EMPLOYEE_ID, EMPLOYEE_NAME, DEPARTMENT, EMPLOYMENT_STATUS, TERMINATION_DATE)
ON t.EMPLOYEE_ID = s.EMPLOYEE_ID
WHEN NOT MATCHED THEN INSERT (EMPLOYEE_ID, EMPLOYEE_NAME, DEPARTMENT, EMPLOYMENT_STATUS, TERMINATION_DATE)
VALUES (s.EMPLOYEE_ID, s.EMPLOYEE_NAME, s.DEPARTMENT, s.EMPLOYMENT_STATUS, s.TERMINATION_DATE);

MERGE INTO APPLICATIONS AS t
USING (SELECT * FROM VALUES
    ('APP01', 'Finance Reporting System', 'HIGH'),
    ('APP02', 'Internal Knowledge Portal', 'LOW')
) AS s (APPLICATION_ID, APPLICATION_NAME, CRITICALITY)
ON t.APPLICATION_ID = s.APPLICATION_ID
WHEN NOT MATCHED THEN INSERT (APPLICATION_ID, APPLICATION_NAME, CRITICALITY)
VALUES (s.APPLICATION_ID, s.APPLICATION_NAME, s.CRITICALITY);

MERGE INTO ACCESS_GRANTS AS t
USING (SELECT * FROM VALUES
    ('G001', 'E101', 'APP01', 'READ', TRUE, NULL),
    ('G002', 'E102', 'APP02', 'ADMIN', TRUE, '2026-09-25'),
    ('G003', 'E103', 'APP01', 'ADMIN', TRUE, '2026-09-20'),
    ('G004', 'E104', 'APP02', 'READ', FALSE, NULL),
    ('G005', 'E105', 'APP02', 'READ', TRUE, NULL),
    ('G006', 'E999', 'APP01', 'ADMIN', TRUE, NULL)
) AS s (GRANT_ID, EMPLOYEE_ID, APPLICATION_ID, ACCESS_LEVEL, IS_ACTIVE, ACCESS_EXPIRY_DATE)
ON t.GRANT_ID = s.GRANT_ID
WHEN NOT MATCHED THEN INSERT (GRANT_ID, EMPLOYEE_ID, APPLICATION_ID, ACCESS_LEVEL, IS_ACTIVE, ACCESS_EXPIRY_DATE)
VALUES (s.GRANT_ID, s.EMPLOYEE_ID, s.APPLICATION_ID, s.ACCESS_LEVEL, s.IS_ACTIVE, s.ACCESS_EXPIRY_DATE);

-- 5. Data-quality checks: all rows should have ISSUE_COUNT = 0.
-- If not, investigate before trusting dashboard counts. No automatic deletion.

CREATE OR REPLACE VIEW VW_DATA_QUALITY_CHECKS AS
SELECT 'EMPLOYEES_DUPLICATE_ID' AS CHECK_NAME, COUNT(*) AS ISSUE_COUNT
FROM (SELECT EMPLOYEE_ID FROM EMPLOYEES GROUP BY EMPLOYEE_ID HAVING COUNT(*) > 1)
UNION ALL
SELECT 'EMPLOYEES_MISSING_REQUIRED', COUNT(*) FROM EMPLOYEES
WHERE NULLIF(TRIM(EMPLOYEE_ID), '') IS NULL OR NULLIF(TRIM(EMPLOYEE_NAME), '') IS NULL OR NULLIF(TRIM(DEPARTMENT), '') IS NULL OR NULLIF(TRIM(EMPLOYMENT_STATUS), '') IS NULL
UNION ALL
SELECT 'APPLICATIONS_DUPLICATE_ID' AS CHECK_NAME, COUNT(*) AS ISSUE_COUNT
FROM (SELECT APPLICATION_ID FROM APPLICATIONS GROUP BY APPLICATION_ID HAVING COUNT(*) > 1)
UNION ALL
SELECT 'APPLICATIONS_MISSING_REQUIRED', COUNT(*) FROM APPLICATIONS
WHERE NULLIF(TRIM(APPLICATION_ID), '') IS NULL OR NULLIF(TRIM(APPLICATION_NAME), '') IS NULL OR NULLIF(TRIM(CRITICALITY), '') IS NULL
UNION ALL
SELECT 'ACCESS_GRANTS_DUPLICATE_ID' AS CHECK_NAME, COUNT(*) AS ISSUE_COUNT
FROM (SELECT GRANT_ID FROM ACCESS_GRANTS GROUP BY GRANT_ID HAVING COUNT(*) > 1)
UNION ALL
SELECT 'ACCESS_GRANTS_MISSING_REQUIRED', COUNT(*) FROM ACCESS_GRANTS
WHERE NULLIF(TRIM(GRANT_ID), '') IS NULL OR NULLIF(TRIM(EMPLOYEE_ID), '') IS NULL OR NULLIF(TRIM(APPLICATION_ID), '') IS NULL OR NULLIF(TRIM(ACCESS_LEVEL), '') IS NULL OR IS_ACTIVE IS NULL
UNION ALL
SELECT 'INVALID_EMPLOYEE_STATUS', COUNT(*) FROM EMPLOYEES WHERE EMPLOYMENT_STATUS NOT IN ('ACTIVE', 'TERMINATED')
UNION ALL
SELECT 'INVALID_ACCESS_LEVEL', COUNT(*) FROM ACCESS_GRANTS WHERE ACCESS_LEVEL NOT IN ('READ', 'ADMIN')
UNION ALL
SELECT 'INVALID_CRITICALITY', COUNT(*) FROM APPLICATIONS WHERE CRITICALITY NOT IN ('LOW', 'MEDIUM', 'HIGH')
UNION ALL
SELECT 'MISSING_APPLICATION', COUNT(*) FROM ACCESS_GRANTS a LEFT JOIN APPLICATIONS app ON a.APPLICATION_ID = app.APPLICATION_ID WHERE app.APPLICATION_ID IS NULL
UNION ALL
SELECT 'TERMINATED_WITHOUT_DATE', COUNT(*) FROM EMPLOYEES WHERE EMPLOYMENT_STATUS = 'TERMINATED' AND TERMINATION_DATE IS NULL;
SELECT * FROM VW_DATA_QUALITY_CHECKS ORDER BY CHECK_NAME;

-- 6. Detection rules. These are demo rules, not Fidelity policies.
-- Unmatched employees need investigation; they are not confirmed violations.

CREATE OR REPLACE VIEW VW_TERMINATED_ACTIVE_ACCESS AS
SELECT
    a.GRANT_ID,
    e.EMPLOYEE_ID,
    e.EMPLOYEE_NAME,
    e.TERMINATION_DATE,
    a.APPLICATION_ID,
    a.ACCESS_LEVEL,
    CASE
        WHEN a.ACCESS_LEVEL = 'ADMIN' THEN 'HIGH'
        ELSE 'MEDIUM'
    END AS RISK_PRIORITY
FROM EMPLOYEES AS e
JOIN ACCESS_GRANTS AS a
    ON e.EMPLOYEE_ID = a.EMPLOYEE_ID
WHERE e.EMPLOYMENT_STATUS = 'TERMINATED'
  AND a.IS_ACTIVE = TRUE;

CREATE OR REPLACE VIEW VW_UNMATCHED_ACTIVE_ACCESS AS
SELECT
    a.GRANT_ID,
    a.EMPLOYEE_ID,
    a.APPLICATION_ID,
    a.ACCESS_LEVEL,
    'Employee record not found' AS FINDING
FROM ACCESS_GRANTS AS a
LEFT JOIN EMPLOYEES AS e
    ON a.EMPLOYEE_ID = e.EMPLOYEE_ID
WHERE a.IS_ACTIVE = TRUE
  AND e.EMPLOYEE_ID IS NULL;

CREATE OR REPLACE VIEW VW_EXPIRED_ACTIVE_ACCESS AS
SELECT
    GRANT_ID,
    EMPLOYEE_ID,
    APPLICATION_ID,
    ACCESS_LEVEL,
    ACCESS_EXPIRY_DATE,
    DATEDIFF(
        'day',
        ACCESS_EXPIRY_DATE,
        cfg.ASSESSMENT_DATE
    ) AS DAYS_PAST_EXPIRY
FROM ACCESS_GRANTS
CROSS JOIN VW_ASSESSMENT_CONFIG AS cfg
WHERE IS_ACTIVE = TRUE
  AND ACCESS_EXPIRY_DATE < cfg.ASSESSMENT_DATE;

-- 7. One row per grant per triggered rule (not one row per person).

CREATE OR REPLACE VIEW VW_ACCESS_FINDINGS AS
SELECT GRANT_ID, EMPLOYEE_ID, APPLICATION_ID, ACCESS_LEVEL,
    'TERMINATED_ACTIVE_ACCESS' AS FINDING_TYPE
FROM VW_TERMINATED_ACTIVE_ACCESS
UNION ALL
SELECT GRANT_ID, EMPLOYEE_ID, APPLICATION_ID, ACCESS_LEVEL,
    'EMPLOYEE_NOT_FOUND' AS FINDING_TYPE
FROM VW_UNMATCHED_ACTIVE_ACCESS
UNION ALL
SELECT GRANT_ID, EMPLOYEE_ID, APPLICATION_ID, ACCESS_LEVEL,
    'EXPIRED_ACTIVE_ACCESS' AS FINDING_TYPE
FROM VW_EXPIRED_ACTIVE_ACCESS;

CREATE OR REPLACE VIEW VW_ACCESS_FINDINGS_DETAIL AS
SELECT
    f.GRANT_ID,
    f.EMPLOYEE_ID,
    e.EMPLOYEE_NAME,
    e.EMPLOYMENT_STATUS,
    f.APPLICATION_ID,
    app.APPLICATION_NAME,
    app.CRITICALITY AS APPLICATION_CRITICALITY,
    f.ACCESS_LEVEL,
    f.FINDING_TYPE
FROM VW_ACCESS_FINDINGS AS f
LEFT JOIN EMPLOYEES AS e
    ON f.EMPLOYEE_ID = e.EMPLOYEE_ID
LEFT JOIN APPLICATIONS AS app
    ON f.APPLICATION_ID = app.APPLICATION_ID;

-- 8. KPI grain: distinct active grants. Zero denominator -> NULL, not 0%.
CREATE OR REPLACE VIEW VW_ACCESS_KPI AS
WITH active_grants AS (
    SELECT DISTINCT GRANT_ID FROM ACCESS_GRANTS
    WHERE IS_ACTIVE = TRUE AND GRANT_ID IS NOT NULL
), flagged_grants AS (
    SELECT DISTINCT GRANT_ID FROM VW_ACCESS_FINDINGS
)
SELECT
    COUNT(*) AS ACTIVE_ACCESS_COUNT,
    COUNT(f.GRANT_ID) AS FLAGGED_ACCESS_COUNT,
    ROUND(100.0 * COUNT(f.GRANT_ID) / NULLIF(COUNT(*), 0), 1)
        AS FLAGGED_ACCESS_PCT
FROM active_grants a
LEFT JOIN flagged_grants f ON a.GRANT_ID = f.GRANT_ID;

CREATE OR REPLACE VIEW VW_FINDING_SUMMARY AS
SELECT
    FINDING_TYPE,
    CASE FINDING_TYPE
        WHEN 'EXPIRED_ACTIVE_ACCESS' THEN 'Expired access'
        WHEN 'TERMINATED_ACTIVE_ACCESS' THEN 'Terminated employee'
        WHEN 'EMPLOYEE_NOT_FOUND' THEN 'Employee not found'
        ELSE FINDING_TYPE
    END AS FINDING_CATEGORY,
    COUNT(*) AS FINDING_COUNT,
    COUNT(DISTINCT GRANT_ID) AS AFFECTED_ACCESS_COUNT
FROM VW_ACCESS_FINDINGS
GROUP BY FINDING_TYPE;

-- 9. Presentation queries: run separately to choose which result to chart.
SELECT * FROM VW_ACCESS_KPI;
SELECT * FROM VW_ACCESS_FINDINGS_DETAIL ORDER BY GRANT_ID, FINDING_TYPE;
SELECT FINDING_CATEGORY, FINDING_COUNT
FROM VW_FINDING_SUMMARY
ORDER BY FINDING_COUNT DESC, FINDING_CATEGORY;

-- 10. Read-only demo checks. FAIL can mean existing data differs from seed data.
SELECT 'TOTAL_FINDINGS' AS CHECK_NAME, COUNT(*) AS ACTUAL, 4 AS EXPECTED,
    CASE WHEN COUNT(*) = 4 THEN 'PASS' ELSE 'FAIL' END AS RESULT
FROM VW_ACCESS_FINDINGS
UNION ALL
SELECT 'FLAGGED_GRANTS', COUNT(DISTINCT GRANT_ID), 3,
    CASE WHEN COUNT(DISTINCT GRANT_ID) = 3 THEN 'PASS' ELSE 'FAIL' END
FROM VW_ACCESS_FINDINGS
UNION ALL
SELECT 'G003_OVERLAPPING_RULES', COUNT(*), 2,
    CASE WHEN COUNT(*) = 2 THEN 'PASS' ELSE 'FAIL' END
FROM VW_ACCESS_FINDINGS WHERE GRANT_ID = 'G003'
UNION ALL
SELECT 'ACTIVE_GRANTS', ACTIVE_ACCESS_COUNT, 5,
    CASE WHEN ACTIVE_ACCESS_COUNT = 5 THEN 'PASS' ELSE 'FAIL' END
FROM VW_ACCESS_KPI
UNION ALL
SELECT 'FLAGGED_PERCENT', FLAGGED_ACCESS_PCT, 60,
    CASE WHEN FLAGGED_ACCESS_PCT = 60 THEN 'PASS' ELSE 'FAIL' END
FROM VW_ACCESS_KPI;

